def render_active(snapshot: dict, code: str, player_id: str) -> None:
    mission = snapshot["mission"]
    remaining = mission["remaining_seconds"]
    mm, ss = divmod(max(0, remaining), 60)
    timer_class = "timer-value timer-danger" if remaining <= 20 else "timer-value"

    render_top_metrics(snapshot)
    st.markdown(
        f"""
        <div class="mission-header">
          <div class="mission-number">RECOVERY STEP {mission['number']:02d} // {escape(mission['template'])}</div>
          <div class="mission-title">{escape(mission['title'])}</div>
          <div class="mission-subtitle">{escape(mission['subtitle'])}</div>
        </div>
        <div class="timer-wrap"><div class="terminal-label">RECOVERY WINDOW</div><div class="{timer_class}">{mm:02d}:{ss:02d}</div></div>
        """,
        unsafe_allow_html=True,
    )

    clue_col, action_col = st.columns([1.35, 1], gap="large")
    with clue_col:
        st.markdown('<div class="section-title">YOUR PRIVATE TERMINAL</div>', unsafe_allow_html=True)
        for i, clue in enumerate(mission["viewer_clues"], start=1):
            op = " operator" if "PRIMARY CONTROL" in clue else ""
            st.markdown(
                f'<div class="clue-card{op}"><div class="clue-index">DATA PACKET {i:02d}</div><div class="clue-text">{escape(clue)}</div></div>',
                unsafe_allow_html=True,
            )
        st.markdown('<div class="small-note">Other operators have different packets. Do not refresh expecting to reveal theirs—the clue split is intentional.</div>', unsafe_allow_html=True)

    with action_col:
        designated = player_id == mission["operator_player_id"]
        badge = "PRIMARY OPERATOR" if designated else "BACKUP TRANSMITTER"
        st.markdown(
            f'<div class="terminal-card"><div class="terminal-label">{badge}</div><h3>Authorization Console</h3><p class="small-note">Enter only the final numeric authorization code your crew agrees on.</p></div>',
            unsafe_allow_html=True,
        )
        with st.form(f"solution_{code}_{mission['number']}", clear_on_submit=True):
            answer = st.text_input("Authorization code", max_chars=8, placeholder="••••", help="Letters/spaces are ignored; most recovery codes are 4–5 digits.")
            transmit = st.form_submit_button("Transmit override", type="primary", use_container_width=True)
        if transmit:
            try:
                result = manager.submit_solution(code, player_id, answer)
                if result["correct"]:
                    set_notice(f"Override accepted. +{result['points']:,} crew points.")
                else:
                    set_error(f"Override rejected. Station integrity −{result['damage']}%.")
                st.rerun()
            except GameError as exc:
                set_error(str(exc))
                st.rerun()
        st.markdown(f'<div class="small-note">Attempts this step: <span class="mono">{mission["attempts"]}</span></div>', unsafe_allow_html=True)
        render_chat(snapshot, code, player_id)


def render_result(snapshot: dict, code: str, player_id: str) -> None:
    mission = snapshot["mission"]
    is_host = player_id == snapshot["host_player_id"]
    render_top_metrics(snapshot)
    success = mission["status"] == "SUCCESS"
    banner_class = "success-banner" if success else "failure-banner"
    title = "SYSTEM RESTORED" if success else "RECOVERY STEP FAILED"
    subtitle = (
        f"Authorization confirmed · +{mission['points_awarded']:,} crew points"
        if success
        else escape(mission.get("failure_reason") or "The system rejected the recovery window.")
    )
    st.markdown(
        f'<div class="{banner_class}"><div class="banner-title">{title}</div><div class="banner-sub">{subtitle}</div></div>',
        unsafe_allow_html=True,
    )
    st.markdown(f'<div class="mission-title">{escape(mission["title"])}</div>', unsafe_allow_html=True)
    st.markdown(
        f'<div class="terminal-card"><div class="terminal-label">CONFIRMED AUTHORIZATION</div><div class="room-code" style="font-size:2.3rem">{escape(mission["solution"] or "—")}</div><div class="small-note">Crew attempts: {mission["attempts"]}</div></div>',
        unsafe_allow_html=True,
    )
    st.markdown('<div class="section-title">CREW</div>', unsafe_allow_html=True)
    render_players(snapshot, player_id)

    label = "Seal mission report" if mission["number"] >= 5 else f"Launch recovery step {mission['number'] + 1}"
    if st.button(label, type="primary", use_container_width=True):
        if safe_run(lambda: manager.launch_next_mission(code, player_id)):
            st.rerun()
    if not is_host:
        st.caption("Any active operator may continue if the commander is unavailable.")
    render_chat(snapshot, code, player_id)


def render_complete(snapshot: dict, code: str, player_id: str) -> None:
    is_host = player_id == snapshot["host_player_id"]
    failed = snapshot["integrity"] <= 0
    status = "MISSION FAILED" if failed else "RIFT CONTAINED"
    kicker = "ORION-7 LOST" if failed else "SYSTEM RESTORED // CREW SYNCHRONIZED"
    st.markdown(f'<div class="rift-kicker">{kicker}</div>', unsafe_allow_html=True)
    st.markdown(f'<div class="rift-logo" style="font-size:clamp(2.8rem,8vw,6rem)">{status}</div>', unsafe_allow_html=True)
    st.markdown(
        '<p class="rift-subtitle">Your final score is shared across the entire crew. The mission only succeeds when the team combines what no single screen can reveal.</p>',
        unsafe_allow_html=True,
    )
    render_top_metrics(snapshot)

    successes = sum(1 for x in snapshot["mission_history"] if x["status"] == "SUCCESS")
    attempts = sum(x["attempts"] for x in snapshot["mission_history"])
    st.markdown(
        f"""
        <div class="metric-grid">
          <div class="metric-card"><div class="metric-label">Systems Restored</div><div class="metric-value">{successes}/5</div></div>
          <div class="metric-card"><div class="metric-label">Total Transmissions</div><div class="metric-value">{attempts}</div></div>
          <div class="metric-card"><div class="metric-label">Crew</div><div class="metric-value">{len(snapshot['players'])} operators</div></div>
        </div>
        """,
        unsafe_allow_html=True,
    )
    st.markdown('<div class="section-title">FINAL CREW ROSTER</div>', unsafe_allow_html=True)
    render_players(snapshot, player_id)

    replay_label = "Run another mission" if is_host else "Reset room for another mission"
    if st.button(replay_label, type="primary", use_container_width=True):
        if safe_run(lambda: manager.play_again(code, player_id)):
            st.rerun()

    if st.button("Exit to mission control", use_container_width=True):
        manager.leave_room(code, player_id)
        st.session_state.room_code = None
        st.query_params.clear()
        st.rerun()


@st.fragment(run_every="1s")
def room_surface() -> None:
    code = st.session_state.get("room_code")
    player_id = st.session_state.player_id
    if not code:
        return
    try:
        manager.reconnect(code, player_id)
        snapshot = manager.get_snapshot(code, player_id)
    except GameError:
        st.session_state.room_code = None
        set_error("That mission room is no longer active.")
        st.rerun()
        return

    show_messages()
    state = snapshot["state"]
    if state == "LOBBY":
        render_lobby(snapshot, code, player_id)
    elif state == "BRIEFING":
        render_briefing(snapshot, code, player_id)
    elif state == "ACTIVE":
        render_active(snapshot, code, player_id)
    elif state == "RESULT":
        render_result(snapshot, code, player_id)
    elif state == "COMPLETE":
        render_complete(snapshot, code, player_id)


if st.session_state.get("room_code"):
    room_surface()
else:
    home_page()
