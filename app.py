def render_chat(snapshot: dict, code: str, player_id: str) -> None:
    st.markdown('<div class="section-title">TEAM COMMS</div>', unsafe_allow_html=True)
    if not snapshot["chat"]:
        st.markdown('<div class="small-note">No transmissions yet. Share only what your terminal shows you.</div>', unsafe_allow_html=True)
    else:
        for msg in snapshot["chat"][-8:]:
            st.markdown(
                f'<div class="chat-message"><div class="chat-name">{escape(msg["player_name"])}</div><div class="chat-text">{escape(msg["text"])}</div></div>',
                unsafe_allow_html=True,
            )
    with st.form(f"chat_form_{code}", clear_on_submit=True):
        chat_text = st.text_input("Transmission", max_chars=180, label_visibility="collapsed", placeholder="Send a short message to the crew…")
        send = st.form_submit_button("Transmit", use_container_width=True)
    if send and chat_text.strip():
        safe_run(lambda: manager.add_chat(code, player_id, chat_text))


def render_lobby(snapshot: dict, code: str, player_id: str) -> None:
    is_host = player_id == snapshot["host_player_id"]
    left, right = st.columns([1.35, 1], gap="large")
    with left:
        st.markdown('<div class="rift-kicker">MISSION LOBBY // ORION-7</div>', unsafe_allow_html=True)
        st.markdown(f'<div class="room-code">{escape(code)}</div>', unsafe_allow_html=True)
        st.markdown('<div class="room-caption">Share this code with your crew. Every operator joins from their own device.</div>', unsafe_allow_html=True)
        qr = qr_image_for_room(code)
        if qr:
            st.image(qr, width=170, caption="Scan to join this room")
        else:
            st.markdown('<div class="small-note">QR join activates automatically after the public deployment URL is configured.</div>', unsafe_allow_html=True)
        st.markdown('<div class="section-title">CREW STATUS</div>', unsafe_allow_html=True)
        render_players(snapshot, player_id)

    with right:
        st.markdown('<div class="terminal-card"><div class="terminal-label">MISSION READINESS</div><h3>Distributed Control Protocol</h3><p class="small-note">Every screen will reveal different evidence. Your crew must communicate to reconstruct each authorization code.</p></div>', unsafe_allow_html=True)
        st.metric("Operators connected", f"{len(snapshot['players'])} / 6")
        if len(snapshot["players"]) < 2:
            st.info("Waiting for at least one more operator.")
        elif is_host:
            if st.button("Begin mission briefing", type="primary", use_container_width=True):
                if safe_run(lambda: manager.start_game(code, player_id)):
                    st.rerun()
        else:
            st.info("Crew ready. Waiting for the commander to begin.")
        if st.button("Leave room", use_container_width=True):
            manager.leave_room(code, player_id)
            st.session_state.room_code = None
            st.query_params.clear()
            st.rerun()


