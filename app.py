def query_value(key: str) -> str:
    value = st.query_params.get(key, "")
    if isinstance(value, list):
        value = value[0] if value else ""
    return str(value).strip()


def init_session() -> None:
    # Keep a lightweight reconnect token in the URL. Invite links generated by the app
    # contain only the room code, so a player's private token is not shared with teammates.
    query_player = query_value("player")
    st.session_state.setdefault("player_id", query_player or secrets.token_urlsafe(10))
    st.session_state.setdefault("room_code", None)
    st.session_state.setdefault("player_name", "")
    st.session_state.setdefault("notice", None)
    st.session_state.setdefault("error", None)

    query_room = query_value("room").upper()[:4]
    if not st.session_state.room_code and query_room and query_player:
        if manager.reconnect(query_room, st.session_state.player_id):
            st.session_state.room_code = query_room
            try:
                snapshot = manager.get_snapshot(query_room, st.session_state.player_id)
                me = next((p for p in snapshot["players"] if p["id"] == st.session_state.player_id), None)
                if me:
                    st.session_state.player_name = me["name"]
            except GameError:
                st.session_state.room_code = None


init_session()


def show_messages() -> None:
    if st.session_state.get("notice"):
        st.success(st.session_state.pop("notice"))
    if st.session_state.get("error"):
        st.error(st.session_state.pop("error"))


def set_error(message: str) -> None:
    st.session_state.error = message


def set_notice(message: str) -> None:
    st.session_state.notice = message


def safe_run(action, success_message: str | None = None) -> bool:
    try:
        action()
        if success_message:
            set_notice(success_message)
        return True
    except GameError as exc:
        set_error(str(exc))
        return False


