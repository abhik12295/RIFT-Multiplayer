def qr_image_for_room(code: str) -> bytes | None:
    public_url = os.getenv("PUBLIC_URL", "").strip()
    if not public_url:
        try:
            public_url = str(st.secrets.get("PUBLIC_URL", "")).strip()
        except Exception:
            public_url = ""
    public_url = public_url.rstrip("/")
    if not public_url:
        return None
    url = f"{public_url}/?{urlencode({'room': code})}"
    img = qrcode.make(url)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def render_players(snapshot: dict, viewer_id: str) -> None:
    for p in snapshot["players"]:
        host = p["id"] == snapshot["host_player_id"]
        you = p["id"] == viewer_id
        label = f"{escape(p['name'])}{' · YOU' if you else ''}"
        role = "COMMANDER" if host and snapshot["state"] == "LOBBY" else escape(p.get("role") or "CREW")
        dot_class = "dot" if p.get("connected", True) else "dot offline"
        st.markdown(
            f"""
            <div class="player-row">
              <div class="player-main"><span class="{dot_class}"></span><span class="player-name">{label}</span></div>
              <span class="role-chip">{role}</span>
            </div>
            """,
            unsafe_allow_html=True,
        )


